interface MigrationSpec {
  readonly dir: string;
  readonly from: string | null;
  readonly to: string;
  readonly invariants?: readonly string[];
  readonly migrationTs?: boolean;
}

function migrationFiles(spec: MigrationSpec, snapshotsRelative: string): Record<string, string> {
  const ops = [
    {
      id: `migration.${spec.dir.split('/').at(-1)}`,
      label: 'Fixture operation',
      operationClass: 'additive' as const,
      execute: [{ description: 'fixture', sql: 'SELECT 1' }],
    },
  ];
  const metadata = {
    from: spec.from,
    to: spec.to,
    providedInvariants: spec.invariants ?? [],
    createdAt: '2026-01-01T00:00:00.000Z',
  };
  const files: Record<string, string> = {
    [`${spec.dir}/migration.json`]: `${JSON.stringify(
      { ...metadata, migrationHash: computeMigrationHash(metadata, ops) },
      null,
      2,
    )}\n`,
    [`${spec.dir}/ops.json`]: `${JSON.stringify(ops, null, 2)}\n`,
  };
  if (spec.migrationTs) {
    const imports = [
      `import type { Contract as End } from '${snapshotsRelative}/${spec.to}/contract';`,
      `import endContract from '${snapshotsRelative}/${spec.to}/contract.json' with { type: 'json' };`,
    ];
    if (spec.from)
      imports.push(
        `import type { Contract as Start } from '${snapshotsRelative}/${spec.from}/contract';`,
        `import startContract from '${snapshotsRelative}/${spec.from}/contract.json' with { type: 'json' };`,
      );
    files[`${spec.dir}/migration.ts`] = [
      ...imports,
      '',
      `export const contracts = { start: ${spec.from ? 'startContract' : 'null'}, end: endContract };`,
      `export type Contracts = { start: ${spec.from ? 'Start' : 'never'}; end: End };`,
      '',
    ].join('\n');
  }
  return files;
}

function ref(hash: string, invariants: readonly string[] = []): string {
  return `${JSON.stringify({ hash, invariants }, null, 2)}\n`.replace(
    /"invariants": \[\n\s+([^\n]*)\n\s+\]/,
    '"invariants": [$1]',
  );
}

function writeTree(root: string, files: Record<string, string>): void {
  for (const [path, content] of Object.entries(files)) {
    const file = join(root, path);
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, content);
  }
}

function writeCase(name: string, build: (format: Format) => Record<string, string>): void {
  writeTree(join(fixturesRoot, name, 'before'), build('old'));
  writeTree(join(fixturesRoot, name, 'after'), build('new'));
}

function writeUnchangedCase(name: string, files: Record<string, string>): void {
  writeTree(join(fixturesRoot, name, 'before'), files);
}

interface ContractFiles {
  readonly hash: string;
  readonly contract: JsonObject;
  readonly dts: string;
}

function contractFiles(spec: ContractSpec, format: Format, storedHash?: string): ContractFiles {
  const hash = storedHash ?? storageHashOf(spec, format);
  return {
    hash,
    contract: contractObject(spec, format, hash),
    dts: contractDts(spec, format, hash),
  };
}

