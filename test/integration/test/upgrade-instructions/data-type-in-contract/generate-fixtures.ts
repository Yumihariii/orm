function typeName(spec: { nativeType: string; dataType: string }, format: Format): JsonObject {
  return format === 'old' ? { nativeType: spec.nativeType } : { dataType: spec.dataType };
}

function columnJson(column: ColumnSpec, format: Format): JsonObject {
  const value: Record<string, Json> = {
    codecId: column.codecId,
    ...typeName(column, format),
    nullable: column.nullable,
  };
  if (column.typeParams) value['typeParams'] = column.typeParams;
  if (column.typeRef) value['typeRef'] = column.typeRef;
  if (column.functionDefault)
    value['default'] = { kind: 'function', expression: column.functionDefault };
  if (column.literalDefault)
    value['default'] = { kind: 'literal', value: column.literalDefault[format] };
  return value;
}

function storageJson(spec: ContractSpec, format: Format): Record<string, Json> {
  const tables: Record<string, Json> = {};
  for (const [tableName, columns] of Object.entries(spec.tables)) {
    tables[tableName] = {
      columns: Object.fromEntries(
        columns.map((column) => [column.name, columnJson(column, format)]),
      ),
      primaryKey: { columns: [columns[0]?.name ?? 'id'] },
      uniques: [],
      indexes: [],
      foreignKeys: [],
    };
  }
  const namespace =
    spec.layout === 'tables'
      ? { id: 'public', tables }
      : {
          id: 'public',
          kind: spec.target === 'postgres' ? 'postgres-schema' : 'sqlite-schema',
          entries: { table: tables },
        };
  const storage: Record<string, Json> = { namespaces: { public: namespace } };
  if (spec.types) {
    storage['types'] = Object.fromEntries(
      spec.types.map((type) => [
        type.name,
        {
          codecId: type.codecId,
          kind: 'codec-instance',
          ...typeName(type, format),
          ...(type.typeParams ? { typeParams: type.typeParams } : {}),
        },
      ]),
    );
  }
  return storage;
}

function storageHashOf(spec: ContractSpec, format: Format): string {
  return computeStorageHash({
    target: spec.target,
    targetFamily: 'sql',
    storage: storageJson(spec, format),
    ...sqlContractCanonicalizationHooks,
  });
}

function contractObject(spec: ContractSpec, format: Format, storageHash: string): JsonObject {
  const contract = {
    targetFamily: 'sql',
    target: spec.target,
    profileHash: PROFILE_HASH,
    roots: {},
    domain: { namespaces: { public: { models: {} } } },
    storage: { ...storageJson(spec, format), storageHash },
    capabilities: { sql: { returning: true } },
    extensions: spec.extensions?.(format) ?? {},
    meta: {},
  };
  const canonical = canonicalizeContractToObject(blindContract(contract), {
    schemaVersion: '1',
    serializeContract: (value) => JSON.parse(JSON.stringify(value)),
    ...sqlContractCanonicalizationHooks,
  });
  return JSON.parse(JSON.stringify({ ...canonical, _generated: GENERATED }));
}

function blindContract(value: unknown): Contract {
  return value as Contract;
}

function emittedJson(contract: JsonObject): string {
  return JSON.stringify(contract, null, 2);
}

function snapshotJson(contract: JsonObject): string {
  return `${canonicalizeJson(contract)}\n`;
}

function dtsLiteral(value: string): string {
  return `'${value}'`;
}

function dtsColumn(column: ColumnSpec, format: Format, indent: string): string {
  const lines = [
    `${indent}readonly ${column.name}: {`,
    format === 'old'
      ? `${indent}  readonly nativeType: ${dtsLiteral(column.nativeType)};`
      : `${indent}  readonly dataType: ${dtsLiteral(column.dataType)};`,
    `${indent}  readonly codecId: ${dtsLiteral(column.codecId)};`,
    `${indent}  readonly nullable: ${column.nullable};`,
  ];
  if (column.functionDefault)
    lines.push(
      `${indent}  readonly default: { readonly kind: 'function'; readonly expression: '${column.functionDefault}' };`,
    );
  if (column.literalDefault) {
    const literal = format === 'old' ? column.literalDefault.oldTs : column.literalDefault.newTs;
    lines.push(
      `${indent}  readonly default: {`,
      `${indent}    readonly kind: 'literal';`,
      `${indent}    readonly value: DefaultLiteralValue<'${column.codecId}', ${literal}>;`,
      `${indent}  };`,
    );
  }
  if (column.typeParams) {
    const params = Object.entries(column.typeParams)
      .map(([key, value]) => `readonly ${key}: ${JSON.stringify(value).replaceAll('"', "'")}`)
      .join('; ');
    lines.push(`${indent}  readonly typeParams: { ${params} };`);
  }
  if (column.typeRef) lines.push(`${indent}  readonly typeRef: '${column.typeRef}';`);
  lines.push(`${indent}};`);
  return lines.join('\n');
}

function dtsType(type: TypeSpec, format: Format): string {
  const params = type.typeParams
    ? `{ ${Object.entries(type.typeParams)
        .map(([key, value]) => `readonly ${key}: ${JSON.stringify(value)}`)
        .join('; ')} }`
    : 'Record<string, never>';
  return [
    `      readonly ${type.name}: {`,
    `        readonly kind: 'codec-instance';`,
    `        readonly codecId: '${type.codecId}';`,
    format === 'old'
      ? `        readonly nativeType: '${type.nativeType}';`
      : `        readonly dataType: '${type.dataType}';`,
    `        readonly typeParams: ${params};`,
    '      };',
  ].join('\n');
}

function contractDts(spec: ContractSpec, format: Format, storageHash: string): string {
  const facade = spec.target === 'postgres' ? '@prisma/orm-postgres' : '@prisma/orm-sqlite';
  const tables = Object.entries(spec.tables)
    .map(([tableName, columns]) =>
      [
        `            readonly ${tableName}: {`,
        '              columns: {',
        ...columns.map((column) => dtsColumn(column, format, '                ')),
        '              };',
        '            };',
      ].join('\n'),
    )
    .join('\n');
  const types = spec.types
    ? ['    readonly types: {', ...spec.types.map((type) => dtsType(type, format)), '    };']
    : [];
  return [
    '// ⚠️  GENERATED FILE - DO NOT EDIT',
    "// This file is automatically generated by 'prisma contract emit'.",
    `import type { CodecTypes } from '${facade}/target/codec-types';`,
    `import type { ProfileHashBase, StorageHashBase } from '${facade}/contract/types';`,
    '',
    'export type StorageHash =',
    `  StorageHashBase<'${storageHash}'>;`,
    'export type ProfileHash =',
    `  ProfileHashBase<'${PROFILE_HASH}'>;`,
    'type DefaultLiteralValue<CodecId extends string, _Encoded> = CodecId extends keyof CodecTypes',
    "  ? CodecTypes[CodecId]['output']",
    '  : _Encoded;',
    '',
    'export type Contract = {',
    '  readonly storage: {',
    '    readonly namespaces: {',
    '      readonly public: {',
    '        readonly entries: {',
    '          readonly table: {',
    tables,
    '          };',
    '        };',
    '      };',
    '    };',
    ...types,
    '    readonly storageHash: StorageHash;',
    '  };',
    ...(spec.extensions ? extensionsDts(format) : []),
    '};',
    '',
  ].join('\n');
}

